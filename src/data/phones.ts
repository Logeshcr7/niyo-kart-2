export function calculateAlgorithmScore(phone: PhoneSpecs, weights: AlgorithmWeights): number {
  const totalWeight = weights.performance + weights.camera + weights.battery + weights.display + weights.value;
  if (totalWeight === 0) return 0;

  const weightedSum =
    phone.scores.performance * weights.performance +
    phone.scores.camera * weights.camera +
    phone.scores.battery * weights.battery +
    phone.scores.display * weights.display +
    phone.scores.value * weights.value;

  return Math.round((weightedSum / totalWeight) * 10) / 10;
}
